/* Builds js/maps/flags.js (the flags shown as faces in `pairs`, `sort` and `map`) from SVG files.
   Only needed when the flags change; the site itself never runs it and makes no outside requests.

   1. Download each flag from Wikimedia Commons into one folder, named by its code (fr.svg, …), e.g.
        https://commons.wikimedia.org/wiki/Special:FilePath/Flag_of_France.svg
      Use only files whose licence on Commons is public domain (check "LicenseShortName" with the Commons API).
      The countries are the named ones in tools/build-world-map.js, with these exceptions:
        es   Flag_of_Spain_(Civil).svg (the civil flag: the one with the coat of arms is far too big)
        om   left out: Oman's flag on Commons is under Oman's own licence, not public domain
        af   left out until reviewers decide which flag to show (see curriculum/world.md, "Neutrality and safety")
      and Iran's two flags, which lessons never show directly (only the one the parent chose, B.flagSvg("iran")):
        iran-current    Flag_of_Iran.svg
        iran-lion-sun   State_flag_of_Iran_(1964–1980).svg
   2. Install svgo (a development tool only): npm i svgo
   3. node tools/build-flags.js <folder with the SVG files> <path to the svgo package>

   Each flag is minified (svgo, coordinates rounded to what shows at card size) and stored as its SVG markup. */
var fs = require("fs");
var path = require("path");

var dir = process.argv[2], svgo = require(process.argv[3] || "svgo");
if (!dir) { console.error("usage: node tools/build-flags.js <folder> [svgo]"); process.exit(1); }
var root = path.join(__dirname, "..");
var LEFT_OUT = ["om", "af"];
// Flags whose emblem stays right with whole numbers (checked by eye): far smaller.
var PRECISION = { mx: 0, tm: 0 };

var codes = fs.readdirSync(dir).filter(function (f) { return /\.svg$/.test(f); }).map(function (f) { return f.slice(0, -4); })
  .filter(function (c) { return LEFT_OUT.indexOf(c) === -1; }).sort();
var out = codes.map(function (code) {
  var src = fs.readFileSync(path.join(dir, code + ".svg"), "utf8");
  var vb = src.match(/viewBox="[\d.\s-]+\s([\d.]+)\s[\d.]+"/), w = src.match(/<svg[^>]*\swidth="([\d.]+)/);
  var width = +(vb ? vb[1] : w ? w[1] : 100);
  // Round to about a three-hundredth of the flag's width: invisible at any size a lesson shows it. Flags that draw
  // small shapes and scale them up (Iran's emblem) keep one decimal.
  var precision = code in PRECISION ? PRECISION[code] : /matrix\(|scale\(/.test(src) ? 1 : Math.max(0, Math.ceil(Math.log10(300 / width)));
  var min = svgo.optimize(src, { multipass: true, floatPrecision: precision, plugins: [
    { name: "preset-default", params: { overrides: { removeViewBox: false } } },
    "removeDimensions", "removeXMLNS", { name: "removeAttrs", params: { attrs: ["data-name"] } },
    // Many flags can be on one page: ids and classes get the flag's code so they never clash.
    { name: "prefixIds", params: { prefix: "flag-" + code, delim: "-" } }] }).data;
  if (!/viewBox/.test(min)) throw new Error(code + ": no viewBox");
  return "  " + JSON.stringify(code) + ": " + JSON.stringify(min);
});
var src = "/* باغچه — flags for `pairs`, `sort` and `map` (B.flagSvg and B.flagFace in js/steps/world.js). Generated by\n" +
  "   tools/build-flags.js; do not edit by hand. Source: Wikimedia Commons, public-domain flag files (each file's\n" +
  "   licence checked), minified. Iran's two flags are used only through the parent's choice in «بخش والدین»\n" +
  "   (\"iran-current\": the current flag, \"iran-lion-sun\": the lion-and-sun flag); lessons ask for \"iran\".\n" +
  "   Left out: " + LEFT_OUT.join(", ") + " (see tools/build-flags.js). */\n" +
  "var B = window.B || {};\nwindow.B = B;\n\nB.FLAGS = {\n" + out.join(",\n") + "\n};\n";
fs.writeFileSync(path.join(root, "js", "maps", "flags.js"), src);
console.log("js/maps/flags.js: " + codes.length + " flags, " + src.length + " bytes");
